"use client";

import Card from "@/components/common/Card";
import Table from "@/components/common/Table";
import { COLUMNTYPES } from "@/constants/column";
import { useApiCall } from "@/hooks/api-call";
import { useAsyncEffect } from "@/hooks/async-effect";
import usePagination from "@/hooks/pagination";
import { toast } from "react-toastify";
import { useState } from "react";
import DropDownButtons from "@/components/common/DropDownButtons";
import confirm from "@/components/common/Confirm";
import { getAllThirteenthMonth, generateThirteenthMonthMonthlyAllocationEntries, downloadExcelFile } from "@/api/reports/reports-13th-month";
import { useModal } from "@/hooks/modal";
import ViewThirteenthMonthPayModal from "./ViewThirteenthMonthPayModal";
import MonthAndYearSelectionModal from "./MonthAndYearSelectionModal";
import YearSelectionModal from "./YearSelectionModal";
import { useFilter } from "@/hooks/use-filter";
import { useFormik } from "formik";
import moment from "moment";
import Grid from "@/components/common/Grid";
import Dropdown from "@/components/common/Dropdown";
import Button from "@/components/common/Button";
import ViewThirteenthMonthMonthlyAllocationModal from "./ViewThirteenthMonthMonthlyAllocationModal";
import ActionDropDown from "@/components/common/ActionDropDown";

const ThirteenthMonthTableCard = () => {
    const api = useApiCall();
    const paginator = usePagination(10);
    const [data] = useState<any>({});
    const viewThirteenthMonthPayModal = useModal();
    const viewMonthlyAllocationModal = useModal();
    const filter = useFilter();
    const monthAndYearSelectionModal = useModal();
    const yearSelectionModal = useModal();
    const [selectedMonthPayId, setSelectedMonthPayId] = useState<string | null>(null);
    const [selectedMonthlyAllocationId, setSelectedMonthlyAllocationId] = useState<string | null>(null);

    const typeOption = [
        {
            label: "13th Month Pay",
            value: "thirteenth_month_pay"
        },
        {
            label: "13th Month Monthly Allocation",
            value: "thirteenth_month_monthly_allocation"
        }
    ];

    const columnSettings = [
        {
            columnHead: "Year",
            path: "year",
            columnType: COLUMNTYPES.string
        },
        {
            columnHead: "File Name",
            path: "file_name",
            columnType: COLUMNTYPES.string
        },
        {
            columnHead: "Generated by",
            path: "user.full_name",
            columnType: COLUMNTYPES.string
        },
        {
            columnHead: "Date",
            path: "created_at",
            columnType: COLUMNTYPES.timestamp,
        },
        {
            columnHead: "Action",
            path: "action",
            columnType: COLUMNTYPES.function,
            function: (data: any) => {
                let actions = [];

                actions.push({
                    label: "Download",
                    onClick: async (data: any) => {
                        try {
                            const response = await downloadExcelFile(data.file_name);
                            const url = window.URL.createObjectURL(new Blob([response.data]));
                            const link = document.createElement('a');
                            link.href = url;
                            link.setAttribute('download', data.file_name);
                            document.body.appendChild(link);
                            link.click();
                            link.remove();
                            window.URL.revokeObjectURL(url);
                        } catch (error) {
                            toast.error("Error downloading file.");
                            console.error("Download error:", error);
                        }
                    },
                    permission: "generate_13th_month_pay"
                });

                actions.push({
                    label: "View",
                    onClick: (data: any) => {
                        if (data.type === "thirteenth_month_pay") {
                            setSelectedMonthPayId(data.id);
                            viewThirteenthMonthPayModal.onOpen();
                        }

                        if (data.type === "thirteenth_month_monthly_allocation") {
                            setSelectedMonthlyAllocationId(data.id);
                            viewMonthlyAllocationModal.onOpen();
                        }
                    }
                });

                const type = data.type;

                if (type === "thirteenth_month_monthly_allocation") {
                    actions.push({
                        label: "Generate Entry",
                        onClick: async () => {
                            const isConfirmed = await confirm({
                                title: "Generate Monthly Allocation Entries",
                                message: "Are you sure you want to generate monthly allocation entries?",
                            });

                            if (isConfirmed) {
                                generateThirteenthMonthMonthlyAllocationEntries(data.id)
                                .then((resp) => {
                                    if (!resp.error) {
                                        toast.success(resp.data.message);
                                        api.triggerReload();
                                    } else {
                                        toast.error(resp.data.message);
                                    }
                                }).catch(() => {
                                    toast.error("Error encountered");
                                });
                            }
                        }
                    });
                }

                return actions.length > 0 ? 
                <ActionDropDown 
                    data={data} 
                    actions={actions} 
                /> : "—";
            }
        }
    ];

    const globalActionSettings = [
        {
            label: "Generate 13th Month Pay",
            onClick: async () => {
                yearSelectionModal.onOpen();
            },
            permission: "generate_13th_month_pay"
        },
        {
            label: "Generate 13th Month Monthly Allocation",
            onClick: async () => {
                monthAndYearSelectionModal.onOpen();
            },
            permission: "generate_13th_month_pay"
        },
    ];

    const formHandler = useFormik({
        initialValues: {
            type: "",
            year: moment().year(),
        },
        validateOnChange: false,
        onSubmit: async (values, { setSubmitting }) => {
            api.triggerReload();
            filter.onReload();
            filter.setFilters(values);
            setSubmitting(true);
        }
    });

    useAsyncEffect(() => {
        api.setLoading(true);
        getAllThirteenthMonth({
            page: paginator.page,
            per_page: paginator.per_page,
            ...formHandler.values 
        })
        .then((resp) => {
            if (resp.error) {
                toast.error("Error fetching 13 month files");
            } else {
                api.setDataSet(resp.data.data);
                paginator.setPage(resp.data.current_page);
                paginator.setPaginationData(resp.data);
            }
        })
        .catch(() => {
            toast.error("Error encountered");
        })
        .finally(() => {
            api.setLoading(false);
        });
    }, [paginator.reload, api.reload, filter.reload]);

    return (
        <>
            <Card>
                <p className=" font-semibold text-red-800">Filters</p>
                <form onSubmit={formHandler.handleSubmit}>
                    <Grid cols={4}>
                        <Dropdown
                            placeholder="select year"
                            label="Year"
                            name="year"
                            value={String(formHandler.values.year)}
                            onChange={formHandler.handleChange}
                            options={Array.from(
                                { length: new Date().getFullYear() - 2017 + 1 }, 
                                (_, i) => {
                                    const year = new Date().getFullYear() - i; 
                                    return { label: year.toString(), value: year.toString() };
                                }
                            )}
                        />
                        <Dropdown
                            placeholder="select type"
                            label="Type"
                            name="type"
                            value={formHandler.values.type}
                            onChange={formHandler.handleChange}
                            options={typeOption}
                        />
                    </Grid>
                    <div className="flex justify-end gap-x-2">
                        <div className="w-[100px]">
                            <Button
                                type="submit"
                                label="Search"
                                onClick={() => {}}
                            />    
                        </div>
                        <div className="w-[100px]">
                            <Button
                                label="Reset"
                                type="button"
                                onClick={() => {
                                    formHandler.resetForm();
                                    formHandler.submitForm();
                                }}
                                variant="secondary"
                            />    
                        </div>
                    </div>
                </form>
            </Card>
            <Card>
                <div className="flex justify-end gap-x-3">
                    <DropDownButtons
                        actions={globalActionSettings}
                    />
                </div>
                <Table
                    dataSet={api.dataSet}
                    columnSettings={columnSettings}
                    loading={api.loading}
                    paginator={paginator}
                />
            </Card>

            <ViewThirteenthMonthPayModal
                modal={viewThirteenthMonthPayModal}
                id={selectedMonthPayId}
            />

            <ViewThirteenthMonthMonthlyAllocationModal
                modal={viewMonthlyAllocationModal}
                id={selectedMonthlyAllocationId}
            />

            <MonthAndYearSelectionModal
                modal={monthAndYearSelectionModal}
                onSubmitCallback={api.triggerReload}
                id={selectedMonthPayId}
            />

            <YearSelectionModal
                modal={yearSelectionModal}
                onSubmitCallback={api.triggerReload}
            />
        </>
    );
};

export default ThirteenthMonthTableCard;