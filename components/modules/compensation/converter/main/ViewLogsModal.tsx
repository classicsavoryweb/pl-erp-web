import Grid from "@/components/common/Grid";
import Modal from "@/components/common/Modal";
import Table from "@/components/common/Table";
import Textfield from "@/components/common/Textfield";
import { COLUMNTYPES } from "@/constants/column";
import { useFormik } from "formik";
import moment from "moment";
import * as Yup from "yup";

interface ModalInterface {
    modal: any;
    data: any;
}

const ViewLogsModal = ({
    modal,
    data,
}: ModalInterface) => {

    return (
        <Modal
            size="md"
            isShowing = {modal.isShowing}
            onClose = {() => {
                modal.onClose();
            }}
            title="Batch Converter Logs"
        >
            <Grid cols={2}>
                <Textfield
                    label="Added By"
                    disabled
                    value={data?.added_by?.proper_full_name ?? ""}
                />
                <Textfield
                    label="Added At"
                    disabled
                    value={ moment(data?.created_at).format("MMMM DD, YYYY HH:mm:ss A") ?? ""}
                />
            </Grid>

            { data?.status == "Voided" &&
                <Grid cols={2}>
                    <Textfield
                        label="Voided By"
                        disabled
                        value={data?.voided_by?.proper_full_name ?? ""}
                    />
                    <Textfield
                        label="Voided At"
                        disabled
                        value={moment(data?.voided_at).format("MMMM DD, YYYY HH:mm:ss A")?? ""}
                    />
                </Grid>
            }

            { (data?.status == "Posted" || data?.status == "Generated" || data?.status == "Sent") &&
                <Grid cols={2}>
                    <Textfield
                        label="Posted By"
                        disabled
                        value={data?.posted_by?.proper_full_name ?? ""}
                    />
                    <Textfield
                        label="Posted At"
                        disabled
                        value={moment(data?.posted_at).format("MMMM DD, YYYY HH:mm:ss A")?? ""}
                    />
                </Grid>
            }

            { (data?.status == "Generated" || data?.status == "Sent") &&
                <Grid cols={2}>
                    <Textfield
                        label="Generated By"
                        disabled
                        value={data?.generated_by?.proper_full_name ?? ""}
                    />
                    <Textfield
                        label="Generated At"
                        disabled
                        value={moment(data?.generated_at).format("MMMM DD, YYYY HH:mm:ss A")?? ""}
                    />
                </Grid>
            }

            { data?.status == "Sent" &&
                <Grid cols={2}>
                    <Textfield
                        label="Sent By"
                        disabled
                        value={data?.sent_by?.proper_full_name ?? ""}
                    />
                    <Textfield
                        label="Sent At"
                        disabled
                        value={moment(data?.sent_at).format("MMMM DD, YYYY HH:mm:ss A")?? ""}
                    />
                </Grid>
            }
        </Modal>
    );
};

export default ViewLogsModal;